void TraceWriter::WriteRegisters(uint32_t first_register,
                                 const uint32_t* register_values,
                                 uint32_t register_count,
                                 bool execute_callbacks_on_play) {
  RegistersCommand cmd = {};
  cmd.type = TraceCommandType::kRegisters;
  cmd.first_register = first_register;
  cmd.register_count = register_count;
  cmd.execute_callbacks = execute_callbacks_on_play;

  uint32_t uncompressed_length;
  if (!xe_trace_payload_size(&stream_,register_values,register_count,4,
          UINT32_MAX,&uncompressed_length)) return;
  if (compress_output_) {
    // Write the header now so we reserve space in the buffer.
    size_t encoded_length;
    cmd.encoding_format = MemoryEncodingFormat::kSnappy;
    int64_t header_position = xe_trace_stream_begin(&stream_,&cmd,sizeof(cmd));
    if (header_position < 0) return;

    // Stream the content right to the buffer.
    snappy::ByteArraySource snappy_source(
        reinterpret_cast<const char*>(register_values), uncompressed_length);
    TraceSink snappy_sink(&stream_);
    encoded_length = snappy::Compress(&snappy_source, &snappy_sink);
    cmd.encoded_length = static_cast<uint32_t>(encoded_length);

    // Seek back and overwrite the header with our final size.
    xe_trace_stream_finish(&stream_,header_position,&cmd,sizeof(cmd),encoded_length);
  } else {
    // Uncompressed - write the values directly to the file.
    cmd.encoding_format = MemoryEncodingFormat::kNone;
    cmd.encoded_length = uncompressed_length;
    xe_trace_stream_write(&stream_,&cmd,sizeof(cmd));
    xe_trace_stream_write(&stream_,register_values,uncompressed_length);
  }
}

void TraceWriter::WriteGammaRamp(
    const reg::DC_LUT_30_COLOR* gamma_ramp_256_entry_table,
    const reg::DC_LUT_PWL_DATA* gamma_ramp_pwl_rgb,
    uint32_t gamma_ramp_rw_component) {
  GammaRampCommand cmd = {};
  cmd.type = TraceCommandType::kGammaRamp;
  cmd.rw_component = uint8_t(gamma_ramp_rw_component);

  constexpr uint32_t k256EntryTableUncompressedLength =
      sizeof(reg::DC_LUT_30_COLOR) * 256;
  constexpr uint32_t kPWLUncompressedLength =
      sizeof(reg::DC_LUT_PWL_DATA) * 3 * 128;
  constexpr uint32_t kUncompressedLength =
      k256EntryTableUncompressedLength + kPWLUncompressedLength;
  uint32_t bytes;
  if (!xe_trace_payload_size(&stream_,gamma_ramp_256_entry_table,
          k256EntryTableUncompressedLength,1,UINT32_MAX,&bytes) ||
      !xe_trace_payload_size(&stream_,gamma_ramp_pwl_rgb,
          kPWLUncompressedLength,1,UINT32_MAX,&bytes)) return;
  if (compress_output_) {
    // Write the header now so we reserve space in the buffer.
    size_t encoded_length;
    cmd.encoding_format = MemoryEncodingFormat::kSnappy;
    int64_t header_position = xe_trace_stream_begin(&stream_,&cmd,sizeof(cmd));
    if (header_position < 0) return;

    // Stream the content right to the buffer.
    TraceSource snappy_source(gamma_ramp_256_entry_table,
        k256EntryTableUncompressedLength,gamma_ramp_pwl_rgb,kPWLUncompressedLength);
    TraceSink snappy_sink(&stream_);
    encoded_length = snappy::Compress(&snappy_source,&snappy_sink);
    cmd.encoded_length = static_cast<uint32_t>(encoded_length);

    // Seek back and overwrite the header with our final size.
    xe_trace_stream_finish(&stream_,header_position,&cmd,sizeof(cmd),encoded_length);
  } else {
    // Uncompressed - write the values directly to the file.
    cmd.encoding_format = MemoryEncodingFormat::kNone;
    cmd.encoded_length = kUncompressedLength;
    xe_trace_stream_write(&stream_,&cmd,sizeof(cmd));
    xe_trace_stream_write(&stream_,gamma_ramp_256_entry_table,k256EntryTableUncompressedLength);
    xe_trace_stream_write(&stream_,gamma_ramp_pwl_rgb,kPWLUncompressedLength);
  }
}
