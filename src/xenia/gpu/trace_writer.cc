void TraceWriter::WritePacketStart(uint32_t base_ptr, uint32_t count) {
  if (!is_open()) {
    return;
  }
  uint32_t bytes;
  if (!xe_trace_payload_size(&stream_,membase_,count,4,
          (UINT64_C(1)<<32)-base_ptr,&bytes)) return;
  PacketStartCommand cmd = {
      TraceCommandType::kPacketStart,
      base_ptr,
      count,
  };
  xe_trace_stream_write(&stream_,&cmd,sizeof(cmd));
  xe_trace_stream_write(&stream_,membase_ + base_ptr,bytes);
}

