TraceWriter::TraceWriter(uint8_t* membase) : membase_(membase) {}
TraceWriter::~TraceWriter() { Close(); }

bool TraceWriter::Open(const char* path, uint32_t title_id) {
  Close();
  if (!xe_trace_stream_open(&stream_,path)) return false;
  TraceHeader header = {};
  header.version = kTraceFormatVersion;
  std::memcpy(header.build_commit_sha, XE_BUILD_COMMIT,
              sizeof(header.build_commit_sha));
  header.title_id = title_id;
  if (!xe_trace_stream_write(&stream_,&header,sizeof(header))) {
    Close(); return false;
  }
  return true;
}
void TraceWriter::Flush() { xe_trace_stream_flush(&stream_); }
void TraceWriter::Close() {
  cached_memory_reads_.clear(); xe_trace_stream_close(&stream_);
}

